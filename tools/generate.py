import fileinput, re, os, sys, operator


DATA_DIR = 'data/ucd'
TESTS_DATA_DIR = 'tests/data'
README_NAME = "ReadMe.txt"
UNICODE_DATA_NAME = "UnicodeData.txt"
DERIVED_BIDI_CLASS_NAME = "extracted/DerivedBidiClass.txt"
BIDI_BRACKETS_NAME = "BidiBrackets.txt"
# The Unicode version the tables and the test data are generated from.
# Delete data/ucd and tests/data before changing it, since files already
# there are not fetched again.
UNIDATA_SOURCE = "18.0.0/ucd"
TABLES_PATH = os.path.join("src", "char_data", "tables.rs")

PREAMBLE = '''// NOTE:
// The following code was generated by "tools/generate.py". do not edit directly

#![allow(missing_docs, non_upper_case_globals, non_snake_case)]
#![cfg_attr(rustfmt, rustfmt_skip)]
'''

# these are the surrogate codepoints, which are not valid rust characters
surrogate_codepoints = (0xD800, 0xDFFF)

def fetch(name, dst):
    if not os.path.exists(dst):
        os.system("curl -fsSL -o '%s' 'https://www.unicode.org/Public/%s/%s'" % (dst, UNIDATA_SOURCE, name))
    if not os.path.exists(dst):
        sys.stderr.write("cannot fetch %s" % name)
        exit(1)

def fetch_data(name):
    dst = os.path.join(DATA_DIR, os.path.basename(name))
    fetch(name, dst)

def fetch_test_data(name):
    dst = os.path.join(TESTS_DATA_DIR, os.path.basename(name))
    fetch(name, dst)

def open_data(name):
    return open(os.path.join(DATA_DIR, os.path.basename(name)))

def is_surrogate(n):
    return surrogate_codepoints[0] <= n <= surrogate_codepoints[1]

def load_bidi_pairs(on_decomps):
    fetch_data(BIDI_BRACKETS_NAME)
    arr = []
    for line in fileinput.input(os.path.join(DATA_DIR, BIDI_BRACKETS_NAME)):
        data = line.split(';');
        if len(data) != 3:
            continue
        if not data[2].strip().startswith("o"):
            # Only make a map of opening to closing, we can
            # get the reverse from it
            continue
        cp1 = int(data[0], 16);
        cp2 = int(data[1], 16);
        decomp = None
        if cp1 in on_decomps:
            decomp = int(on_decomps[cp1], 16)
        arr += [(cp1, cp2, decomp)]
    return arr

# Returns (group_categories, on_decomps),
# where on_decomps is a map containing canonical equivalents for
# ON characters only, and group_categories is the result of group_categories()
# on bidi properties
def load_unicode_data():
    fetch_data(UNICODE_DATA_NAME)
    # Decompositions of all characters that have a canonical one
    on_decomps = {}
    for line in fileinput.input(os.path.join(DATA_DIR, UNICODE_DATA_NAME)):
        data = line.split(';')
        if len(data) != 15:
            continue
        decomp = data[5]
        if len(decomp) != 0 and " " not in decomp:
            on_decomps[int(data[0], 16)] = decomp

    return (group_categories(load_bidi_classes()), on_decomps)

# Returns a map from each Bidi_Class value to the codepoints that have it,
# for every codepoint except the surrogates.
#
# DerivedBidiClass.txt gives the default value of the unassigned codepoints
# in its @missing lines, a later line overriding an earlier one where they
# overlap, and the value of every other codepoint in its data lines.
# <https://www.unicode.org/reports/tr44/#Missing_Conventions>
def load_bidi_classes():
    fetch_data(DERIVED_BIDI_CLASS_NAME)
    long_names = {
        "Arabic_Letter": "AL", "Arabic_Number": "AN",
        "Paragraph_Separator": "B", "Boundary_Neutral": "BN",
        "Common_Separator": "CS", "European_Number": "EN",
        "European_Separator": "ES", "European_Terminator": "ET",
        "First_Strong_Isolate": "FSI", "Left_To_Right": "L",
        "Left_To_Right_Embedding": "LRE", "Left_To_Right_Isolate": "LRI",
        "Left_To_Right_Override": "LRO", "Nonspacing_Mark": "NSM",
        "Other_Neutral": "ON", "Pop_Directional_Format": "PDF",
        "Pop_Directional_Isolate": "PDI", "Right_To_Left": "R",
        "Right_To_Left_Embedding": "RLE", "Right_To_Left_Isolate": "RLI",
        "Right_To_Left_Override": "RLO", "Segment_Separator": "S",
        "White_Space": "WS",
    }

    def parse(fields):
        cps, value = [f.strip() for f in fields.split(';')[:2]]
        value = long_names.get(value, value)
        assert value in long_names.values(), value
        bounds = cps.split('..')
        start = int(bounds[0], 16)
        end = int(bounds[-1], 16)
        return (start, end, value)

    missing = []
    assigned = []
    with open_data(DERIVED_BIDI_CLASS_NAME) as f:
        for line in f:
            if line.startswith("# @missing:"):
                missing.append(parse(line[len("# @missing:"):].split('#')[0]))
                continue
            line = line.split('#')[0].strip()
            if line:
                assigned.append(parse(line))
    assert missing, "DerivedBidiClass.txt has no @missing lines"

    value_of = {}
    for (start, end, value) in missing + assigned:
        for code in range(start, end + 1):
            value_of[code] = value

    bidi_class = {}
    for code in range(0, 0x110000):
        if is_surrogate(code):
            continue
        bidi_class.setdefault(value_of[code], []).append(code)
    return bidi_class

def group_categories(cats):
    cats_out = []
    for cat in cats:
        cats_out.extend([(x, y, cat) for (x, y) in group_cat(cats[cat])])
    cats_out.sort(key=lambda w: w[0])
    return (sorted(cats.keys()), cats_out)

def group_cat(cat):
    cat_out = []
    letters = sorted(set(cat))
    cur_start = letters.pop(0)
    cur_end = cur_start
    for letter in letters:
        assert letter > cur_end, \
            "cur_end: %s, letter: %s" % (hex(cur_end), hex(letter))
        if letter == cur_end + 1:
            cur_end = letter
        else:
            cat_out.append((cur_start, cur_end))
            cur_start = cur_end = letter
    cat_out.append((cur_start, cur_end))
    return cat_out

def format_table_content(f, content, indent):
    line = " "*indent
    first = True
    for chunk in content.split(","):
        if len(line) + len(chunk) < 98:
            if first:
                line += chunk
            else:
                line += ", " + chunk
            first = False
        else:
            f.write(line + ",\n")
            line = " "*indent + chunk
    f.write(line)

def escape_char(c):
    return "'\\u{%x}'" % c

def emit_table(
    file_,
    t_name,
    t_data,
    t_type = "&'static [(char, char)]",
    is_pub=True,
    pfun=lambda x: "(%s,%s)" % (escape_char(x[0]), escape_char(x[1]))
):
    if is_pub:
        file_.write("pub ")
    file_.write("const %s: %s = &[\n" % (t_name, t_type))

    data = ""
    first = True
    for dat in t_data:
        if not first:
            data += ","
        first = False
        data += pfun(dat)
    format_table_content(file_, data, 4)
    file_.write("\n];\n\n")

def emit_bidi_module(file_, bidi_class_table, cats, bidi_pairs_table):
    file_.write("""
#[allow(non_camel_case_types)]
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
/// Represents values of the Unicode character property
/// [`Bidi_Class`](http://www.unicode.org/reports/tr44/#Bidi_Class), also
/// known as the *bidirectional character type*.
///
/// * <http://www.unicode.org/reports/tr9/#Bidirectional_Character_Types>
/// * <http://www.unicode.org/reports/tr44/#Bidi_Class_Values>
pub enum BidiClass {
""")
    for cat in cats:
        file_.write("    " + cat + ",\n")
    file_.write("""}

#[cfg(feature = "hardcoded-data")]
use self::BidiClass::*;

#[cfg(feature = "hardcoded-data")]
""")

    emit_table(
        file_,
        "bidi_class_table",
        bidi_class_table,
        "&'static [(char, char, BidiClass)]",
        pfun=lambda x: "(%s,%s,%s)" % (escape_char(x[0]), escape_char(x[1]), x[2]),
    )

    emit_table(
        file_,
        "bidi_pairs_table",
        bidi_pairs_table,
        "&'static [(char, char, Option<char>)]",
        pfun=lambda x: "(%s,%s,%s)" % (escape_char(x[0]), escape_char(x[1]), "Some(%s)" % escape_char(x[2]) if x[2] else "None"),
    )

def get_unicode_version():
    fetch_data(README_NAME)
    with open_data(README_NAME) as readme:
        pattern = r"for [Vv]ersion (\d+)\.(\d+)\.(\d+) of the\s+Unicode"
        return re.search(pattern, readme.read()).groups()

if __name__ == "__main__":
    # Find Unicode Version
    if not os.path.exists(DATA_DIR):
        os.mkdir(DATA_DIR)
    unicode_version = get_unicode_version()

    # Build data tables
    if os.path.exists(TABLES_PATH):
        os.remove(TABLES_PATH)
    with open(TABLES_PATH, "w") as file_:
        file_.write(PREAMBLE)
        file_.write("""
/// The [Unicode version](http://www.unicode.org/versions/) of data
pub const UNICODE_VERSION: (u64, u64, u64) = (%s, %s, %s);
""" % unicode_version)

        ((bidi_categories, bidi_class_table), on_decomps) = load_unicode_data()
        bidi_pairs_table = load_bidi_pairs(on_decomps)
        emit_bidi_module(file_, bidi_class_table, bidi_categories, bidi_pairs_table)

    # Fetch test data files
    fetch_test_data("BidiTest.txt")
    fetch_test_data("BidiCharacterTest.txt")
